#include "header.h"

void	print_banner(const t_traceroute *tr)
{
	printf("traceroute to %s (%s), %d hops max, %d byte packets\n",
		tr->dest_arg, tr->dest_ip, tr->opt.max_hops, tr->opt.packet_len);
	fflush(stdout);
}
